export type MessageKey = keyof typeof en;
export type MessageValues = Record<string, string | number>;
export function formatMessage(
  language: PromptLanguage,
  key: MessageKey,
  values: MessageValues = {},
) {
  return translations[language][key].replace(
    /\{(\w+)\}/g,
    (placeholder, name: string) =>
      Object.hasOwn(values, name) ? String(values[name]) : placeholder,
  );
}

// Validation retains stable English Error.message values for non-UI consumers.
// The UI formats the key/parameters at render time, including after language changes.
export class UiError extends Error {
  key: MessageKey;
  values: MessageValues;
  constructor(key: MessageKey, values: MessageValues = {}) {
    super(formatMessage("en", key, values));
    this.key = key;
    this.values = values;
  }
}

export function localizeFeedback(
  value: Error | string,
  language: PromptLanguage,
): string {
  if (value instanceof UiError)
    return formatMessage(language, value.key, value.values);
  if (!value) return "";
  const key = (Object.keys(en) as MessageKey[]).find(
    (key) => en[key] === value,
  );
  return key
    ? translations[language][key]
    : translations[language].unknownError;
}
